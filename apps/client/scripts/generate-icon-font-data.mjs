import { existsSync, mkdirSync, readFileSync, statSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const scriptDirectory = path.dirname(fileURLToPath(import.meta.url));
const clientPackageDirectory = path.resolve(scriptDirectory, '..');
const fontsDirectory = path.join(clientPackageDirectory, 'fonts');
const outputDirectory = path.join(clientPackageDirectory, 'src/infrastructure/fonts');
const outputPath = path.join(outputDirectory, 'generated-icon-font-data.ts');

const iconFonts = [
  { familyKey: 'ionicons', fileName: 'Ionicons.ttf' },
  { familyKey: 'material-community', fileName: 'MaterialCommunityIcons.ttf' },
];

function shouldRegenerate() {
  if (process.argv.includes('--force')) {
    return true;
  }

  if (!existsSync(outputPath)) {
    return true;
  }

  const outputModifiedMs = statSync(outputPath).mtimeMs;

  return iconFonts.some(({ fileName }) => {
    const fontPath = path.join(fontsDirectory, fileName);
    return !existsSync(fontPath) || statSync(fontPath).mtimeMs > outputModifiedMs;
  });
}

if (!shouldRegenerate()) {
  console.log(
    `Skipping icon font generation; ${path.relative(clientPackageDirectory, outputPath)} is up to date.`,
  );
  process.exit(0);
}

const missingFont = iconFonts.find(({ fileName }) => !existsSync(path.join(fontsDirectory, fileName)));

if (missingFont) {
  console.error(`Missing icon font file: fonts/${missingFont.fileName}`);
  process.exit(1);
}

const entries = iconFonts.map(({ familyKey, fileName }) => {
  const fontPath = path.join(fontsDirectory, fileName);
  const base64 = readFileSync(fontPath).toString('base64');
  return `  '${familyKey}': '${base64}'`;
});

const fileContents = `/* eslint-disable */
// Generated by apps/client/scripts/generate-icon-font-data.mjs — do not edit.
export const GENERATED_ICON_FONT_BASE64 = {
${entries.join(',\n')},
} as const;
`;

mkdirSync(outputDirectory, { recursive: true });
writeFileSync(outputPath, fileContents, 'utf8');
console.log(`Wrote ${path.relative(clientPackageDirectory, outputPath)}`);
