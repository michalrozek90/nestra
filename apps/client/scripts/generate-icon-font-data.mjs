import { existsSync, mkdirSync, readFileSync, statSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const generatorScriptPath = fileURLToPath(import.meta.url);
const scriptDirectory = path.dirname(generatorScriptPath);
const clientPackageDirectory = path.resolve(scriptDirectory, '..');
const outputDirectory = path.join(clientPackageDirectory, 'src/infrastructure/fonts');
const outputPath = path.join(outputDirectory, 'generated-icon-font-data.ts');

const iconFonts = [
  {
    familyKey: 'ionicons',
    fontModulePath: '@expo/vector-icons/build/vendor/react-native-vector-icons/Fonts/Ionicons.ttf',
    glyphMapModulePath:
      '@expo/vector-icons/build/vendor/react-native-vector-icons/glyphmaps/Ionicons.json',
    testGlyphName: 'leaf-outline',
  },
  {
    familyKey: 'material-community',
    fontModulePath:
      '@expo/vector-icons/build/vendor/react-native-vector-icons/Fonts/MaterialCommunityIcons.ttf',
    glyphMapModulePath:
      '@expo/vector-icons/build/vendor/react-native-vector-icons/glyphmaps/MaterialCommunityIcons.json',
    testGlyphName: 'menu',
  },
];

function resolveModulePath(modulePath) {
  return fileURLToPath(import.meta.resolve(modulePath));
}

function shouldRegenerate() {
  if (process.argv.includes('--force')) {
    return true;
  }

  if (!existsSync(outputPath)) {
    return true;
  }

  const outputModifiedMs = statSync(outputPath).mtimeMs;

  return (
    statSync(generatorScriptPath).mtimeMs > outputModifiedMs ||
    iconFonts.some(
      ({ fontModulePath, glyphMapModulePath }) =>
        statSync(resolveModulePath(fontModulePath)).mtimeMs > outputModifiedMs ||
        statSync(resolveModulePath(glyphMapModulePath)).mtimeMs > outputModifiedMs,
    )
  );
}

if (!shouldRegenerate()) {
  console.log(
    `Skipping icon font generation; ${path.relative(clientPackageDirectory, outputPath)} is up to date.`,
  );
  process.exit(0);
}

const entries = iconFonts.map(
  ({ familyKey, fontModulePath, glyphMapModulePath, testGlyphName }) => {
    const fontPath = resolveModulePath(fontModulePath);
    const glyphMapPath = resolveModulePath(glyphMapModulePath);
    const glyphMap = JSON.parse(readFileSync(glyphMapPath, 'utf8'));
    const testGlyphCodePoint = glyphMap[testGlyphName];

    if (!Number.isInteger(testGlyphCodePoint)) {
      throw new Error(`Missing ${testGlyphName} in ${glyphMapModulePath}`);
    }

    const base64 = readFileSync(fontPath).toString('base64');
    const testString = String.fromCodePoint(testGlyphCodePoint);

    return `  '${familyKey}': { base64: '${base64}', testString: ${JSON.stringify(testString)} }`;
  },
);

const fileContents = `// Generated by apps/client/scripts/generate-icon-font-data.mjs — do not edit.
export const GENERATED_ICON_FONT_BASE64 = {
${entries.join(',\n')},
} as const;
`;

mkdirSync(outputDirectory, { recursive: true });
writeFileSync(outputPath, fileContents, 'utf8');
console.log(`Wrote ${path.relative(clientPackageDirectory, outputPath)}`);
